// Package protodocs writes the API reference pages of docs.gritz.dev from proto
// descriptors: one Starlight Markdown page per message and enum of a package.
// cmd/protoc-gen-gritz-docs runs it as a protoc plugin.
package protodocs

import (
	"errors"
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
)

// editBaseURL is where a page's "Edit page" link points, followed by the proto
// file's path in the buf module, which is the repo's proto/ directory.
const editBaseURL = "https://github.com/gritzapp/gritz/edit/master/proto/"

// Options selects what Generate documents.
type Options struct {
	// Package is the proto package to document, such as "gritz.v1".
	Package protoreflect.FullName
}

// Generate writes a page for every message and enum of opts.Package in gen's
// files, and fails on a comment that can't be rendered or a slug collision.
func Generate(gen *protogen.Plugin, opts Options) error {
	if opts.Package == "" {
		return errors.New("protodocs: no package: pass package=<proto package>")
	}
	g := generator{gen: gen, pkg: opts.Package, written: map[string]protoreflect.FullName{}}
	for _, f := range gen.Files {
		if !f.Generate || f.Desc.Package() != opts.Package {
			continue
		}
		for _, e := range f.Enums {
			if err := g.enum(e); err != nil {
				return err
			}
		}
		for _, m := range f.Messages {
			if err := g.message(m); err != nil {
				return err
			}
		}
	}
	return nil
}

type generator struct {
	gen *protogen.Plugin
	pkg protoreflect.FullName
	// written maps each page's path to the type it documents, to catch two
	// types whose names only differ in case.
	written map[string]protoreflect.FullName
}

func (g *generator) message(m *protogen.Message) error {
	if m.Desc.IsMapEntry() {
		return nil
	}
	for _, e := range m.Enums {
		if err := g.enum(e); err != nil {
			return err
		}
	}
	for _, nested := range m.Messages {
		if err := g.message(nested); err != nil {
			return err
		}
	}

	var b strings.Builder
	g.frontmatter(&b, m.Desc, "message", m.Comments)
	if len(m.Fields) == 0 {
		b.WriteString("This message has no fields.\n")
	} else {
		b.WriteString("## Fields\n\n| Field | Type | Description |\n| --- | --- | --- |\n")
		for _, f := range m.Fields {
			typ, err := fieldType(f.Desc, g.pkg)
			if err != nil {
				return fmt.Errorf("%s: field %s: %w", position(f.Desc), f.Desc.FullName(), err)
			}
			var notes []string
			if f.Desc.Options().(*descriptorpb.FieldOptions).GetDeprecated() {
				notes = append(notes, "Deprecated.")
			}
			if o := f.Desc.ContainingOneof(); o != nil && !o.IsSynthetic() {
				notes = append(notes, fmt.Sprintf("One of `%s`.", o.Name()))
			}
			desc, err := cellDescription(notes, f.Comments)
			if err != nil {
				return fmt.Errorf("%s: field %s: %w", position(f.Desc), f.Desc.FullName(), err)
			}
			row(&b, fmt.Sprintf("`%s`", f.Desc.Name()), typ, desc)
		}
	}
	return g.write(m.Desc, b.String())
}

func (g *generator) enum(e *protogen.Enum) error {
	var b strings.Builder
	g.frontmatter(&b, e.Desc, "enum", e.Comments)
	b.WriteString("## Values\n\n| Name | Number | Description |\n| --- | --- | --- |\n")
	for _, v := range e.Values {
		var notes []string
		if v.Desc.Options().(*descriptorpb.EnumValueOptions).GetDeprecated() {
			notes = append(notes, "Deprecated.")
		}
		desc, err := cellDescription(notes, v.Comments)
		if err != nil {
			return fmt.Errorf("%s: enum value %s: %w", position(v.Desc), v.Desc.FullName(), err)
		}
		row(&b, fmt.Sprintf("`%s`", v.Desc.Name()), fmt.Sprint(v.Desc.Number()), desc)
	}
	return g.write(e.Desc, b.String())
}

// frontmatter writes a page's frontmatter and the type's comment.
func (g *generator) frontmatter(b *strings.Builder, d protoreflect.Descriptor, kind string, comments protogen.CommentSet) {
	name := relName(d, g.pkg)
	lines := docLines(comments)
	description := firstSentence(lines)
	if description == "" {
		description = fmt.Sprintf("The `%s` %s of the gritz API.", name, kind)
	}
	b.WriteString("---\n# Code generated by protoc-gen-gritz-docs. DO NOT EDIT.\n")
	fmt.Fprintf(b, "title: %s\n", yamlString(name))
	fmt.Fprintf(b, "description: %s\n", yamlString(description))
	fmt.Fprintf(b, "editUrl: %s%s\n", editBaseURL, d.ParentFile().Path())
	b.WriteString("---\n\n")
	if text := blockMarkdown(lines); text != "" {
		b.WriteString(text + "\n\n")
	}
}

func (g *generator) write(d protoreflect.Descriptor, content string) error {
	path := strings.TrimPrefix(pageURL(d, g.pkg), "/api/")
	path = strings.TrimSuffix(path, "/") + ".md"
	if other, ok := g.written[path]; ok {
		return fmt.Errorf("%s: %s and %s both have the page %s: their names only differ in case", position(d), other, d.FullName(), path)
	}
	g.written[path] = d.FullName()
	f := g.gen.NewGeneratedFile(path, "")
	_, err := f.Write([]byte(content))
	return err
}

// row writes a table row.
func row(b *strings.Builder, cells ...string) {
	b.WriteString("|")
	for _, c := range cells {
		if c != "" {
			b.WriteString(" " + c)
		}
		b.WriteString(" |")
	}
	b.WriteString("\n")
}

// position is a descriptor's file and line, for errors.
func position(d protoreflect.Descriptor) string {
	loc := d.ParentFile().SourceLocations().ByDescriptor(d)
	return fmt.Sprintf("%s:%d", d.ParentFile().Path(), loc.StartLine+1)
}
